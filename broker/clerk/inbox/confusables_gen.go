//go:build ignore

// confusables_gen writes confusables_table.go from Unicode's confusables.txt
// (UTS #39), the file ASSUMPTIONS.md MIG-3-R4 names by version and SHA-256:
//
//	go run confusables_gen.go confusables.txt | gofmt > confusables_table.go
package main

import (
	"bufio"
	"crypto/sha256"
	"fmt"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	b, err := os.ReadFile(os.Args[1])
	if err != nil {
		panic(err)
	}
	version := ""
	table := map[rune]string{}
	sc := bufio.NewScanner(strings.NewReader(string(b)))
	for sc.Scan() {
		line := strings.TrimPrefix(sc.Text(), "\ufeff")
		if v, ok := strings.CutPrefix(line, "# Version: "); ok {
			version = v
		}
		line, _, _ = strings.Cut(line, "#")
		f := strings.Split(line, ";")
		if len(f) < 3 {
			continue
		}
		src, err := strconv.ParseUint(strings.TrimSpace(f[0]), 16, 32)
		if err != nil {
			panic(line)
		}
		var dst []rune
		for _, h := range strings.Fields(f[1]) {
			r, err := strconv.ParseUint(h, 16, 32)
			if err != nil {
				panic(line)
			}
			dst = append(dst, rune(r))
		}
		if _, dup := table[rune(src)]; dup {
			panic(line)
		}
		table[rune(src)] = string(dst)
	}
	keys := make([]rune, 0, len(table))
	for r := range table {
		keys = append(keys, r)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	fmt.Printf("// Code generated by confusables_gen.go from confusables.txt %s (SHA-256 %x); DO NOT EDIT.\n\n", version, sha256.Sum256(b))
	fmt.Println("package inbox\n\n// confusables maps a code point to its UTS #39 prototype.\nvar confusables = map[rune]string{")
	for _, r := range keys {
		fmt.Printf("\t%#x: %+q,\n", r, table[r])
	}
	fmt.Println("}")
}
