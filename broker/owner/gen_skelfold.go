//go:build ignore

// gen_skelfold writes skelfold_tables.go, the per-code-point tables the
// CH-12 skeleton fold (skelfold.go) runs on, from the Unicode 15.0.0 data
// files (the version Go's unicode package carries):
//
//	go run gen_skelfold.go UnicodeData.txt CaseFolding.txt confusables.txt DerivedCoreProperties.txt
//
// The files come from https://www.unicode.org/Public/15.0.0/ucd/ and
// https://www.unicode.org/Public/security/15.0.0/ (mirrored in
// github.com/unicode-org/unicodetools, unicodetools/data/). Their SHA-256
// sums are checked below, so a regenerated table rests on the same data.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

var sums = map[string]string{
	"UnicodeData.txt":           "806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73",
	"CaseFolding.txt":           "cdd49e55eae3bbf1f0a3f6580c974a0263cb86a6a08daa10fbf705b4808a56f7",
	"confusables.txt":           "2b10130885c3370b101c52d7baedc452ab7f0e257b86c1e52ee657ecfc29ce64",
	"DerivedCoreProperties.txt": "d367290bc0867e6b484c68370530bdd1a08b6b32404601b8c7accaf83e05628d",
}

func main() {
	if len(os.Args) != 5 {
		fail("usage: go run gen_skelfold.go UnicodeData.txt CaseFolding.txt confusables.txt DerivedCoreProperties.txt")
	}
	if unicode.Version != "15.0.0" {
		fail("Go's unicode package is %s, the tables are 15.0.0", unicode.Version)
	}
	ud, cf, conf, dcp := read(os.Args[1]), read(os.Args[2]), read(os.Args[3]), read(os.Args[4])

	// UnicodeData: decompositions, general category, combining class.
	decomp := map[rune][]rune{}
	gc := map[rune]string{}
	ccc := map[rune]int{}
	var first rune = -1
	for _, f := range fields(ud) {
		r := hexRune(f[0])
		if strings.HasSuffix(f[1], ", First>") {
			first = r
			continue
		}
		lo := r
		if strings.HasSuffix(f[1], ", Last>") {
			lo = first
		}
		c, _ := strconv.Atoi(f[3])
		for x := lo; x <= r; x++ {
			gc[x], ccc[x] = f[2], c
		}
		if d := f[5]; d != "" {
			if strings.HasPrefix(d, "<") {
				d = d[strings.Index(d, ">")+1:]
			}
			decomp[r] = hexRunes(d)
		}
	}
	// The tables lean on Go's unicode package for M, letters and digits,
	// and the runtime drops every mark rather than reordering marks, so
	// both must hold for this data.
	for r := rune(0); r <= unicode.MaxRune; r++ {
		g := gc[r]
		if ccc[r] != 0 && g[0] != 'M' {
			fail("U+%04X has ccc %d but category %s", r, ccc[r], g)
		}
		if g != "" && (unicode.Is(unicode.M, r) != (g[0] == 'M') ||
			unicode.IsLetter(r) != (g[0] == 'L') || unicode.IsDigit(r) != (g == "Nd")) {
			fail("U+%04X: Go's unicode package disagrees with UnicodeData (%s)", r, g)
		}
	}

	// CaseFolding: full case folding, statuses C and F.
	fold := map[rune][]rune{}
	for _, f := range fields(cf) {
		if f[1] == "C" || f[1] == "F" {
			fold[hexRune(f[0])] = hexRunes(f[2])
		}
	}

	var nfd, nfkd func(r rune, compat bool) []rune
	nfkd = func(r rune, compat bool) []rune {
		if s := rune(0xAC00); r >= s && r < s+11172 {
			i := r - s
			out := []rune{0x1100 + i/588, 0x1161 + i%588/28}
			if t := i % 28; t != 0 {
				out = append(out, 0x11A7+t)
			}
			return out
		}
		d, ok := decomp[r]
		if !ok || (!compat && isCompat(ud, r)) {
			return []rune{r}
		}
		var out []rune
		for _, x := range d {
			out = append(out, nfkd(x, compat)...)
		}
		return out
	}
	nfd = func(r rune, _ bool) []rune { return nfkd(r, false) }
	nfdS := func(rs []rune) []rune {
		var out []rune
		for _, r := range rs {
			out = append(out, nfd(r, false)...)
		}
		return out
	}

	// kf: NFKD, then case folding, of one code point.
	kf := map[rune]string{}
	// skel: the confusables.txt prototype of one code point, then NFD.
	skel := map[rune]string{}
	proto := map[rune][]rune{}
	for _, f := range fields(conf) {
		proto[hexRune(f[0])] = hexRunes(f[1])
	}
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		var out []rune
		for _, x := range nfkd(r, true) {
			if y, ok := fold[x]; ok {
				out = append(out, y...)
			} else {
				out = append(out, x)
			}
		}
		if !hangul(r) && string(out) != string(r) {
			kf[r] = string(out)
		}
		p, ok := proto[r]
		if !ok {
			p = []rune{r}
		}
		if s := nfdS(p); !(hangul(r) && !ok) && string(s) != string(r) {
			skel[r] = string(s)
		}
	}

	var dicp []rune
	for _, f := range fields(dcp) {
		if f[1] != "Default_Ignorable_Code_Point" {
			continue
		}
		lo, hi, _ := strings.Cut(f[0], "..")
		if hi == "" {
			hi = lo
		}
		for x := hexRune(lo); x <= hexRune(hi); x++ {
			dicp = append(dicp, x)
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_skelfold.go from Unicode 15.0.0; DO NOT EDIT.\n\npackage owner\n\n")
	fmt.Fprintf(&b, "const skelUnicodeVersion = %q\n\n", "15.0.0")
	writeMap(&b, "skelKF", "NFKD then full case folding, where it changes the code point (Hangul syllables are decomposed in code).", kf)
	writeMap(&b, "skelProto", "The confusables.txt prototype then NFD, where it changes the code point (Hangul syllables are decomposed in code).", skel)
	fmt.Fprintf(&b, "// skelDICP is Default_Ignorable_Code_Point.\nvar skelDICP = []skelRange{\n")
	for i := 0; i < len(dicp); {
		j := i
		for j+1 < len(dicp) && dicp[j+1] == dicp[j]+1 {
			j++
		}
		fmt.Fprintf(&b, "{0x%04X, 0x%04X},\n", dicp[i], dicp[j])
		i = j + 1
	}
	fmt.Fprintf(&b, "}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fail("format: %v", err)
	}
	if err := os.WriteFile("skelfold_tables.go", src, 0o644); err != nil {
		fail("%v", err)
	}
}

func hangul(r rune) bool { return r >= 0xAC00 && r < 0xAC00+11172 }

var compatSet map[rune]bool

func isCompat(ud []byte, r rune) bool {
	if compatSet == nil {
		compatSet = map[rune]bool{}
		for _, f := range fields(ud) {
			if strings.HasPrefix(f[5], "<") {
				compatSet[hexRune(f[0])] = true
			}
		}
	}
	return compatSet[r]
}

func writeMap(b *bytes.Buffer, name, doc string, m map[rune]string) {
	keys := make([]rune, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	fmt.Fprintf(b, "// %s is %s\nvar %s = map[rune]string{\n", name, doc, name)
	for _, k := range keys {
		fmt.Fprintf(b, "0x%04X: %s,\n", k, quote(m[k]))
	}
	fmt.Fprintf(b, "}\n\n")
}

// quote writes every non-ASCII code point as an escape, so the table
// reads the same in any editor and holds no invisible characters.
func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r >= 0x20 && r < 0x7F:
			b.WriteRune(r)
		case r <= 0xFFFF:
			fmt.Fprintf(&b, `\u%04X`, r)
		default:
			fmt.Fprintf(&b, `\U%08X`, r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func read(path string) []byte {
	data, err := os.ReadFile(path)
	if err != nil {
		fail("%v", err)
	}
	base := path[strings.LastIndex(path, "/")+1:]
	sum := sha256.Sum256(data)
	if want := sums[base]; want != hex.EncodeToString(sum[:]) {
		fail("%s: sha256 %x, want %s", base, sum, want)
	}
	return data
}

// fields splits a UCD file into its data lines' semicolon fields, comments
// and blank lines dropped, each field trimmed.
func fields(data []byte) [][]string {
	var out [][]string
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		if strings.TrimSpace(line) == "" {
			continue
		}
		f := strings.Split(line, ";")
		for i := range f {
			f[i] = strings.TrimSpace(f[i])
		}
		out = append(out, f)
	}
	return out
}

func hexRune(s string) rune {
	v, err := strconv.ParseUint(s, 16, 32)
	if err != nil {
		fail("bad code point %q", s)
	}
	return rune(v)
}

func hexRunes(s string) []rune {
	var out []rune
	for _, f := range strings.Fields(s) {
		out = append(out, hexRune(f))
	}
	return out
}

func fail(f string, a ...any) {
	fmt.Fprintf(os.Stderr, "gen_skelfold: "+f+"\n", a...)
	os.Exit(1)
}
