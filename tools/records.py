#!/usr/bin/env python3
"""Review records from verdict comments, batched daily after merge (#1691, RECORDS-INLINE #1816).

Each lens verdict is posted as a PR comment. This tool turns the marked comments of merged
PRs into files `reviews/<lens>/YYYY-MM-DD-pr<N>.md`, so one daily bot PR (records.yml) lands
them all; no feature PR carries a record.

A comment is a record only when all of these hold:
  - it carries a marker `<!-- record: <lens> -->` per lens it records, where <lens> is an
    existing directory under reviews/ (a combined comment carries several markers);
  - its author is the repository's owner, a member or a collaborator;
  - its PR is merged;
  - its first non-blank line is a `# ` title and the next one a complete `Record:` line,
    as tools/doclint.py requires (its RECORD_FIELDS);
  - no record for that PR exists yet in that lens directory (a hand-written one wins);
    among several marked comments for one PR and lens, the newest wins.
Anything else is skipped, with a reason for a marked comment. A trusted, unmarked comment whose
first line looks like a verdict (`Verdict: ...`, or a line starting with a review's name and
ending in ACCEPT, CHANGES REQUESTED or REJECT) is reported too, but only when its merged PR has no
marked comment and no record in any lens, and as one line with a count, so a lost record is never
silent and never noisy; the reasons go to stderr and, in Actions, the job summary. The shape is documented, with an example
that tests/test_records.py runs, in docs/OPERATING.md §4 ("Verdict comment shape"). The file body is the comment
without its markers and its trailing `---` footer. Nothing is ever overwritten.

Usage:
  tools/records.py [--since ISO] [--out FILE]   fetch every comment of the PRs merged since ISO
                                                (default: 7 days ago; the window bounds the
                                                merge, not the comment) via GITHUB_TOKEN, print
                                                or write a JSON object {path: content}; also
                                                report PRs merged per day that go to Mark
Standard library only.
"""
import argparse
import datetime
import json
import os
import pathlib
import re
import sys
import urllib.error
import urllib.request

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from doclint import RECORD_FIELDS  # noqa: E402
from premerge import mark_paths  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
MARKER = re.compile(r"<!--\s*record:\s*([a-z0-9-]+)\s*-->")
TRUSTED = ("OWNER", "MEMBER", "COLLABORATOR")
FOOTER = re.compile(r"\n\s*---\s*\n\s*_Generated by \[Claude Code\]\([^)]*\)_\s*$")
PR_URL = re.compile(r"/pulls?/(\d+)$|/issues/(\d+)$")
# `Verdict: accept` first line, or "<Name> review ...: ACCEPT" (name first, verdict last, in capitals).
VERDICT_LINE = re.compile(r"^(?:#\s*)?Verdict:\s*(?:accept|fix-list|reject)\b|"
                          r"^[A-Za-z0-9 ()/.,#-]{0,60}\b(?i:review)\b[^:\n]{0,60}:\s*"
                          r"(?:ACCEPT|CHANGES REQUESTED|REJECT)\W*$")
PATH = re.compile(r"^reviews/[a-z0-9-]+/\d{4}-\d\d-\d\d-pr\d+\.md$")


def pr_of(c):
    m = PR_URL.search(c.get("issue_url", ""))
    return int(m.group(1) or m.group(2)) if m else None


def lenses(root=ROOT):
    return sorted(p.name for p in (root / "reviews").iterdir() if p.is_dir())


def has_record(root, lens, pr):
    return any((root / "reviews" / lens).glob(f"*-pr{pr}.md"))


def body_of(text):
    """Comment text as a record file: markers and the attribution footer removed."""
    text = MARKER.sub("", text.replace("\r\n", "\n"))
    text = FOOTER.sub("", text.rstrip())
    return re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"


def verdict_like(text):
    """True when the first non-blank line reads as a review verdict."""
    first = next((l.strip() for l in (text or "").splitlines() if l.strip()), "")
    return bool(VERDICT_LINE.search(first))


def well_formed(body):
    """A `# ` title directly followed by a complete Record line, found as doclint finds them:
    lines before the title (an L3 verdict's leading `Verdict:` and `Cause:`) are allowed."""
    lines = [l for l in body.splitlines() if l.strip()]
    title = next((i for i, l in enumerate(lines) if l.startswith("# ")), None)
    rec = lines[title + 1] if title is not None and title + 1 < len(lines) else ""
    return rec.startswith("Record:") and all(f.search(rec) for f in RECORD_FIELDS)


def harvest(comments, merged, root=ROOT):
    """Records to add, and reasons for marked comments skipped.

    comments: issue comments as the REST API returns them; merged: the set of merged PR
    numbers among them. Returns ({path: content}, [reason, ...]).
    """
    known, out, skipped = set(lenses(root)), {}, []
    marked = {pr_of(c) for c in comments if MARKER.search(c.get("body") or "")}
    unmarked = {}  # PR -> first unmarked verdict comment
    for c in sorted(comments, key=lambda c: c["created_at"], reverse=True):  # newest verdict wins
        marks = list(dict.fromkeys(MARKER.findall(c.get("body") or "")))
        pr = pr_of(c)
        where = f"comment {c.get('html_url', c.get('id'))}"
        if not marks:
            if pr in merged and c.get("author_association") in TRUSTED and verdict_like(c.get("body")):
                unmarked.setdefault(pr, where)
            continue
        if c.get("author_association") not in TRUSTED:
            skipped.append(f"{where}: author is not owner, member or collaborator")
            continue
        if pr not in merged:
            skipped.append(f"{where}: PR not merged")
            continue
        body = body_of(c["body"])
        if not well_formed(body):
            skipped.append(f"{where}: needs a `# ` title, then a complete `Record:` line")
            continue
        day = c["created_at"][:10]
        for lens in marks:
            if lens not in known:
                skipped.append(f"{where}: no lens directory reviews/{lens}/")
                continue
            if has_record(root, lens, pr) or any(p.startswith(f"reviews/{lens}/") and p.endswith(f"-pr{pr}.md")
                                                 for p in out):
                continue
            path = f"reviews/{lens}/{day}-pr{pr}.md"
            assert PATH.match(path), path
            out[path] = body
    lost = {pr: w for pr, w in unmarked.items()
            if pr not in marked and not any(has_record(root, lens, pr) for lens in known)}
    if lost:
        first = lost[min(lost)]
        skipped.append(f"{len(lost)} merged PR(s) with a verdict comment but no `<!-- record: <lens> -->` "
                       f"marker and no record: {', '.join(f'#{n}' for n in sorted(lost))}; first {first}")
    return out, skipped


def _api(repo, path, token):
    req = urllib.request.Request(
        f"https://api.github.com/repos/{repo}/{path}",
        headers={"Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28",
                 **({"Authorization": f"Bearer {token}"} if token else {})})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


def _paged(repo, path, token, stop=lambda item: False):
    """Items of a paged listing, until a page ends short or `stop(item)` is true."""
    sep, page = ("&" if "?" in path else "?"), 1
    while True:
        batch = _api(repo, f"{path}{sep}per_page=100&page={page}", token)
        for item in batch:
            if stop(item):
                return
            yield item
        if len(batch) < 100:
            return
        page += 1


def fetch(repo, since, token):
    """Verdict-like comments of the PRs merged since `since`, those PRs, and the per-day count of
    them that touch a Mark-only path. The window bounds the merge, not the comment, so a PR merged
    long after its last verdict keeps it (#1838)."""
    comments, merged, routed = [], set(), {}
    # Closed PRs by last update: a merge is an update, so none merged since `since` lies past the stop.
    for pr in _paged(repo, "pulls?state=closed&sort=updated&direction=desc", token,
                     stop=lambda p: p["updated_at"] < since):
        if not pr.get("merged_at") or pr["merged_at"] < since:
            continue
        n = pr["number"]
        merged.add(n)
        comments += [c for c in _paged(repo, f"issues/{n}/comments", token)
                     if MARKER.search(c.get("body") or "") or verdict_like(c.get("body"))]
        if mark_paths(f["filename"] for f in _paged(repo, f"pulls/{n}/files", token)):
            day = pr["merged_at"][:10]
            routed[day] = routed.get(day, 0) + 1
    return comments, merged, routed


def routed_line(routed, merged):
    """The measure: merged PRs per day that touch a Mark-only path (premerge.mark_paths)."""
    days = ", ".join(f"{d} {n}" for d, n in sorted(routed.items())) or "none"
    return f"routed to Mark (of {merged} merged): {sum(routed.values())}; per merge day: {days}"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    week = datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(days=7)
    ap.add_argument("--since", default=week.strftime("%Y-%m-%dT%H:%M:%SZ"))
    ap.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", "ghbmrk/agentOS"))
    ap.add_argument("--out")
    args = ap.parse_args(argv)
    comments, merged, routed = fetch(args.repo, args.since, os.environ.get("GITHUB_TOKEN"))
    out, skipped = harvest(comments, merged)
    for s in skipped:
        print(f"skipped: {s}", file=sys.stderr)
    measure = routed_line(routed, len(merged))
    print(measure, file=sys.stderr)
    if os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(os.environ["GITHUB_STEP_SUMMARY"], "a") as f:
            if skipped:
                f.write("### Verdict comments skipped\n\n" + "".join(f"- {s}\n" for s in skipped))
            f.write(f"### PRs routed to Mark\n\n{measure}\n")
    text = json.dumps(out, indent=1, sort_keys=True)
    if args.out:
        pathlib.Path(args.out).write_text(text + "\n")
    else:
        print(text)
    print(f"{len(out)} record(s)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
